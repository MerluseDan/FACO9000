"""Offline Chromium visual verification of the Ubuntu QR dashboard.

Example/invalid QR for preview only; actual QRs are generated by the server and decoded in test_qr_scan_optional.
"""
import base64
import io
import shutil
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BROWSER = shutil.which('chromium') or shutil.which('google-chrome')
try:
    from playwright.sync_api import sync_playwright
    from qrcode.image.svg import SvgImage
    import qrcode
    AVAILABLE = True
except ImportError:
    AVAILABLE = False


@unittest.skipUnless(AVAILABLE and BROWSER, 'Playwright/QR dependencies or Chromium unavailable')
class AdminLayout(unittest.TestCase):
    def test_ubuntu_dashboard_qr_layout_at_phone_and_desktop_width(self):
        html=(ROOT/'admin/index.html').read_text(encoding='utf8')
        css=(ROOT/'admin/admin.css').read_text(encoding='utf8')
        html=html.replace('<link rel="stylesheet" href="/admin.css" />','<style>'+css+'</style>')
        html=html.replace('<script src="/admin.js" defer></script>','')
        picture = qrcode.make('https://example.invalid/preview-not-a-real-invite',image_factory=SvgImage)
        out=io.BytesIO();picture.save(out)
        source='data:image/svg+xml;base64,'+base64.b64encode(out.getvalue()).decode()
        with sync_playwright() as pw:
            browser=pw.chromium.launch(executable_path=BROWSER,headless=True,
                                       args=['--no-sandbox','--disable-dev-shm-usage'])
            try:
                for width,height in ((390,850),(1280,880)):
                    page=browser.new_page(viewport={'width':width,'height':height})
                    errors=[]
                    page.on('pageerror', lambda e:errors.append(str(e)))
                    page.set_content(html)
                    page.evaluate('''(image) => {
                        document.getElementById('connectionStatus').classList.add('active');
                        document.getElementById('connectionStatus').lastElementChild.textContent='Public link active';
                        document.getElementById('publicUrl').textContent='https://example.invalid';
                        document.getElementById('epochNotice').textContent='Edition 03 · automatic key refresh enabled';
                        document.getElementById('onlineCount').textContent='3 people online';
                        const nav=document.getElementById('guestSlots');
                        for(let i=1;i<=10;i++){
                            const b=document.createElement('button');b.type='button';b.className='slot';
                            if(i===3)b.setAttribute('aria-current','true');
                            const num=String(i).padStart(2,'0');
                            b.innerHTML=`<span class="slot-symbol">${num}</span><span class="slot-copy"><b>Person ${num}</b><small>${i<=3?'Online · Ready':'Personal QR invitation'}</small></span><span class="slot-chevron">›</span>`;
                            nav.append(b);
                        }
                        document.getElementById('selectionType').textContent='PRIVATE PARTICIPANT QR';
                        document.getElementById('selectionTitle').textContent='Person 03';
                        document.getElementById('selectionBadge').textContent='03';
                        document.getElementById('selectionDescription').textContent='Design preview. The example link is not a real invitation.';
                        document.getElementById('qrLoading').classList.add('hidden');
                        const qr=document.getElementById('qrImage');qr.src=image;qr.classList.remove('hidden');
                        document.getElementById('qrCaption').textContent='Private entry · One distinct credential per person';
                        document.getElementById('inviteUrl').value='https://example.invalid/preview-not-a-real-invite';
                        document.getElementById('securityHint').textContent='Preview only. Real invitations are generated securely by your Ubuntu server.';
                        document.getElementById('lastRotated').textContent='Session credentials refresh when Crumble or Cloudflare restarts.';
                        document.getElementById('guestCount').textContent='10';
                        document.getElementById('edition').textContent='Edition 03';
                        document.getElementById('copyButton').disabled=false;
                        document.getElementById('shareButton').disabled=false;
                        document.getElementById('saveButton').disabled=false;
                    }''',source)
                    self.assertEqual(page.locator('.slot').count(),11)
                    self.assertTrue(page.locator('#qrImage').is_visible())
                    self.assertLessEqual(page.evaluate('document.documentElement.scrollWidth'),width+1)
                    self.assertEqual(errors,[])
                    page.screenshot(path=str(ROOT/f'_qa_admin_{width}.png'),full_page=True)
                    page.close()
            finally:
                browser.close()
